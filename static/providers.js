window.getZenServeService = function(slug) {
  if (!slug) return null;
  const s = slug.toLowerCase().trim();
  if (s === 'home-cleaner') return window.ZENSERVE_SERVICES_DIRECTORY['home-cleaning'];
  return window.ZENSERVE_SERVICES_DIRECTORY[s] || null;
};

window.getProvidersForService = function(serviceSlug) {
  if (!serviceSlug || serviceSlug === 'all') return window.providersData || [];
  const s = serviceSlug.toLowerCase().trim();
  const sMap = {
    'plumber': ['plumber'],
    'electrician': ['electrician'],
    'ac-repair': ['ac repair', 'ac-repair'],
    'carpenter': ['carpenter'],
    'painter': ['painter'],
    'home-cleaning': ['home cleaning', 'home cleaner', 'home-cleaner'],
    'home-cleaner': ['home cleaning', 'home cleaner', 'home-cleaner'],
    'labour-work': ['labour work', 'labour-work'],
    'personal-chef': ['personal chef', 'personal-chef'],
    'barber-home': ['barber at home', 'barber-home'],
    'massage-therapy': ['massage therapy', 'massage-therapy'],
    'blood-test': ['blood test at home', 'blood test', 'blood-test'],
    'computer-service': ['computer service', 'computer-service'],
    'camera-rental': ['camera rental', 'camera-rental'],
    'home-tuition': ['home tuition', 'home-tuition']
  };
  const targets = sMap[s] || [s];
  return (window.providersData || []).filter(p => {
    const cat = (p.category || p.service || '').toLowerCase();
    const pSlug = (p.service_slug || '').toLowerCase();
    return targets.includes(cat) || targets.includes(pSlug);
  });
};

window.getProviderById = function(id) {
  if (!id) return null;
  return (window.providersData || []).find(p => String(p.id).toLowerCase() === String(id).toLowerCase()) || null;
};
